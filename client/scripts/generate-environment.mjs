/**
 * Reads client/.env (local) and process.env (CI/Vercel) and generates
 * src/environments/environment.config.ts for Angular build-time injection.
 *
 * Run automatically via prestart / prebuild, or manually: node scripts/generate-environment.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const clientRoot = join(__dirname, '..');
const envPath = join(clientRoot, '.env');
const outPath = join(clientRoot, 'src/environments/environment.config.ts');

const isProductionBuild = process.argv.includes('--production');

function loadDotEnv(filePath) {
  if (!existsSync(filePath)) return {};
  const vars = {};
  const content = readFileSync(filePath, 'utf-8');
  for (const line of content.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    vars[key] = value;
  }
  return vars;
}

function pick(fileVars, keys, fallback) {
  for (const key of keys) {
    const fromFile = fileVars[key];
    if (fromFile !== undefined && fromFile !== '') return fromFile;
    const fromProcess = process.env[key];
    if (fromProcess !== undefined && fromProcess !== '') return fromProcess;
  }
  return fallback;
}

function asBool(value, fallback) {
  if (value === undefined || value === '') return fallback;
  return ['1', 'true', 'yes', 'on'].includes(String(value).toLowerCase());
}

const fileVars = loadDotEnv(envPath);

const devDefaults = {
  graphqlHttpUri: 'http://localhost:4000/graphql',
  graphqlWsUri: 'ws://localhost:4000/graphql',
  auth0Domain: 'YOUR_AUTH0_DOMAIN.auth0.com',
  auth0ClientId: 'YOUR_AUTH0_CLIENT_ID',
  auth0Audience: 'https://task-dashboard-api',
  devAuthBypass: false,
};

const prodDefaults = {
  graphqlHttpUri: 'https://YOUR_API_HOST/graphql',
  graphqlWsUri: 'wss://YOUR_API_HOST/graphql',
  auth0Domain: 'YOUR_AUTH0_DOMAIN.auth0.com',
  auth0ClientId: 'YOUR_AUTH0_CLIENT_ID',
  auth0Audience: 'https://task-dashboard-api',
  devAuthBypass: false,
};

function resolveConfig(defaults) {
  return {
    graphqlHttpUri: pick(fileVars, ['NG_APP_GRAPHQL_HTTP_URI', 'GRAPHQL_HTTP_URI'], defaults.graphqlHttpUri),
    graphqlWsUri: pick(fileVars, ['NG_APP_GRAPHQL_WS_URI', 'GRAPHQL_WS_URI'], defaults.graphqlWsUri),
    auth0Domain: pick(fileVars, ['NG_APP_AUTH0_DOMAIN', 'AUTH0_DOMAIN'], defaults.auth0Domain),
    auth0ClientId: pick(fileVars, ['NG_APP_AUTH0_CLIENT_ID', 'AUTH0_CLIENT_ID'], defaults.auth0ClientId),
    auth0Audience: pick(fileVars, ['NG_APP_AUTH0_AUDIENCE', 'AUTH0_AUDIENCE'], defaults.auth0Audience),
    devAuthBypass: asBool(
      pick(fileVars, ['NG_APP_DEV_AUTH_BYPASS', 'DEV_AUTH_BYPASS'], String(defaults.devAuthBypass)),
      defaults.devAuthBypass,
    ),
  };
}

const development = resolveConfig(devDefaults);
const production = resolveConfig(prodDefaults);

const fileContent = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-environment.mjs — do not edit manually.
// Configure via client/.env (copy from .env.example) or Vercel environment variables.

export interface EnvironmentConfig {
  production: boolean;
  graphqlHttpUri: string;
  graphqlWsUri: string;
  auth0: {
    domain: string;
    clientId: string;
    audience: string;
    redirectUri: string;
  };
  devAuthBypass: boolean;
}

function toEnvironment(cfg: {
  graphqlHttpUri: string;
  graphqlWsUri: string;
  auth0Domain: string;
  auth0ClientId: string;
  auth0Audience: string;
  devAuthBypass: boolean;
}, production: boolean): EnvironmentConfig {
  const redirectUri =
    typeof window !== 'undefined' ? window.location.origin : production ? '' : 'http://localhost:4200';
  return {
    production,
    graphqlHttpUri: cfg.graphqlHttpUri,
    graphqlWsUri: cfg.graphqlWsUri,
    auth0: {
      domain: cfg.auth0Domain,
      clientId: cfg.auth0ClientId,
      audience: cfg.auth0Audience,
      redirectUri,
    },
    devAuthBypass: cfg.devAuthBypass,
  };
}

const devCfg = ${JSON.stringify(development, null, 2)};
const prodCfg = ${JSON.stringify(production, null, 2)};

export const developmentEnvironment = toEnvironment(devCfg, false);
export const productionEnvironment = toEnvironment(prodCfg, true);
`;

writeFileSync(outPath, fileContent, 'utf-8');

const mode = isProductionBuild ? 'production' : 'development';
console.log(`[env] Generated environment.config.ts (${mode} build profile applied on import).`);
if (!existsSync(envPath)) {
  console.log('[env] No client/.env found — using defaults. Copy client/.env.example to client/.env to customize.');
}
